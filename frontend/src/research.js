// Research page: headline numbers, the two architectures, and one card per research question.
import { $ } from "./utils.js";
import { HEADLINES, QUESTIONS } from "./findings.js";
import { drawCell } from "./viz/cell.js";

// Simple diagram of the translator: encoder -> attention -> decoder -> copy gate.
function translatorDiagram() {
  const box = (x, y, w, h, title, sub, fill = "#f8f6f1", stroke = "#d6d1c6") =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="10" fill="${fill}" stroke="${stroke}"/>
     <text x="${x + w / 2}" y="${y + h / 2 - 2}" text-anchor="middle" font-size="14" font-weight="600" fill="#1f1d1a">${title}</text>
     <text x="${x + w / 2}" y="${y + h / 2 + 16}" text-anchor="middle" font-size="11" fill="#57534c">${sub}</text>`;
  const arrow = (x1, y1, x2, y2) =>
    `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="#57534c" stroke-width="1.6" marker-end="url(#a2)"/>`;
  const words = ["thou", "art", "Romeo"];
  let s = `<svg class="cell-svg" viewBox="0 0 610 330"><defs><marker id="a2" viewBox="0 0 10 10" refX="9" refY="5"
    markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#57534c"/></marker></defs>`;
  words.forEach((w, i) => {
    s += `<text x="${70 + i * 80}" y="315" text-anchor="middle" font-size="13" fill="#7b2232" font-weight="600">${w}</text>`;
    s += arrow(70 + i * 80, 298, 70 + i * 80, 262);
  });
  s += box(30, 200, 240, 60, "Encoder", "bidirectional LSTM reads the sentence");
  s += arrow(150, 200, 150, 150);
  s += box(30, 90, 240, 60, "Attention", "which input words matter now?", "#e3eefb", "#2a78d6");
  s += box(340, 200, 240, 60, "Decoder", "LSTM writes one word at a time");
  s += arrow(340, 230, 270, 125);
  s += arrow(270, 115, 340, 115);
  s += box(340, 90, 240, 60, "Copy gate", "copy an input word or write a new one", "#fde9e0", "#eb6834");
  s += arrow(460, 90, 460, 45);
  s += `<text x="460" y="32" text-anchor="middle" font-size="14" fill="#1f1d1a">“you” “are” “Romeo”</text>`;
  s += `<text x="285" y="104" text-anchor="middle" font-size="11" fill="#57534c">context</text>`;
  return s + "</svg>";
}

function figureBlock(q, k) {
  if (!q.figures.length) return `<div class="muted">See the full report for the tables.</div>`;
  const tabs = q.figures.length > 1
    ? `<div class="segmented fig-tabs" data-q="${k}">${q.figures.map(([f, l], i) =>
        `<button data-v="${f}" class="${i ? "" : "active"}">${l}</button>`).join("")}</div>`
    : "";
  const [file, label] = q.figures[0];
  return `<figure>${tabs}<img id="fig-${k}" src="/results/${file}" alt="${label}" loading="lazy" />
    <figcaption>Click to enlarge · generated by the experiment scripts</figcaption></figure>`;
}

export function setupResearch() {
  const headlines = HEADLINES.map(([v, k]) => `<div class="card"><div class="v">${v}</div><div class="k">${k}</div></div>`).join("");
  const questions = QUESTIONS.map((q, k) => `
    <article class="card rq">
      <div>
        <span class="tag">${q.tag}</span>
        <h3>${q.title}</h3>
        <p class="claim">${q.claim}</p>
        <ul>${q.points.map((p) => `<li>${p}</li>`).join("")}</ul>
        <p style="margin-top:12px"><a href="/results/${q.report}" target="_blank" class="muted">Full report (${q.report}) ↗</a></p>
      </div>
      ${figureBlock(q, k)}
    </article>`).join("");

  $("page-research").innerHTML = `
    <div class="page-head">
      <h2>Inside the LSTM: what we found</h2>
      <p>Five experiments on two small recurrent networks trained on a laptop CPU: a character-level
        generator and a word-level translator. Every number comes from the experiment scripts in the repository.</p>
    </div>
    <div class="hero-stats">${headlines}</div>
    <div class="arch">
      <div class="card"><div class="card-title"><h3>The generator's LSTM cell</h3><span class="hint">hand-written in cells.py</span></div>
        <div id="arch-cell"></div></div>
      <div class="card"><div class="card-title"><h3>The translator</h3><span class="hint">translator_model.py</span></div>
        ${translatorDiagram()}
        <p class="muted" style="margin-top:6px">Beam search picks the words: 5 candidates, no repeated words or phrases,
          and a coverage penalty for candidates that ignored an input word. Unknown words (new names) are copied
          from where the attention points.</p></div>
    </div>
    <div class="rq-list">${questions}</div>`;

  drawCell($("arch-cell"), "lstm", { input: 0.8, forget: 0.7, output: 0.4 }, "a");

  // figure tabs + lightbox
  $("page-research").addEventListener("click", (e) => {
    const tab = e.target.closest(".fig-tabs button");
    if (tab) {
      const group = tab.parentElement;
      group.querySelectorAll("button").forEach((b) => b.classList.toggle("active", b === tab));
      $(`fig-${group.dataset.q}`).src = `/results/${tab.dataset.v}`;
      return;
    }
    if (e.target.tagName === "IMG") {
      $("lightbox").querySelector("img").src = e.target.src;
      $("lightbox").style.display = "grid";
    }
  });
  $("lightbox").onclick = () => ($("lightbox").style.display = "none");
}
